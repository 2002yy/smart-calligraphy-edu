"""Conservative filesystem maintenance for attempt-scoped evaluation overlays.

Default behavior is a read-only inventory. An explicit, offline quarantine may
move old orphaned JPEGs outside /uploads; no permanent deletion is performed.
"""
from __future__ import annotations

import json
import os
import re
import time
from pathlib import Path
from urllib.parse import unquote

import sqlalchemy as sa

from app.models.evaluation import Evaluation
from app.models.homework import Homework


DEFAULT_MIN_AGE_SECONDS = 30 * 24 * 3600
ATTEMPT_RE = re.compile(r"^(.+)_result_([0-9a-f]{32})\.jpg$")


def _managed_path(storage_root: Path, image_url: str | None) -> Path | None:
    if not isinstance(image_url, str) or not image_url.startswith("/uploads/"):
        return None
    relative = image_url[len("/uploads/"):]
    # Names generated by save_homework_image use forward-slash components;
    # do not decode URL characters or resolve externally supplied paths.
    if not relative or "\\" in relative or "%" in relative:
        return None
    pieces = Path(relative).parts
    if not pieces or any(p in ("..", ".") for p in pieces):
        return None
    candidate = storage_root.joinpath(*pieces).resolve()
    return candidate if candidate.is_relative_to(storage_root) else None


def _references(db, root: Path):
    """Include live homework/evaluation URLs and archived historical URLs."""
    referenced = set()
    sources = {}
    active = set()
    homework_rows = db.execute(
        sa.select(Homework.id, Homework.image_url, Homework.processed_image_url)
    ).all()
    for hw_id, image_url, processed in homework_rows:
        path = _managed_path(root, image_url)
        if path is not None:
            sources[hw_id] = path
            referenced.add(path)
        processed_path = _managed_path(root, processed)
        if processed_path is not None:
            referenced.add(processed_path)
    for hw_id, status, token, url in db.execute(
        sa.select(
            Evaluation.homework_id, Evaluation.status,
            Evaluation.attempt_id, Evaluation.compare_image_url,
        )
    ):
        if status == "processing" and token:
            active.add((hw_id, token))
        ref_path = _managed_path(root, url)
        if ref_path is not None:
            referenced.add(ref_path)

    # The reconciliation tool can move full historical evaluations into this
    # table. They must remain reachable for a future explicit restore.
    inspector = sa.inspect(db.get_bind())
    if "evaluations_legacy_archive" in inspector.get_table_names():
        table = sa.Table(
            "evaluations_legacy_archive", sa.MetaData(),
            autoload_with=db.get_bind(),
        )
        for snapshot in db.execute(sa.select(table.c.snapshot_json)).scalars():
            if isinstance(snapshot, dict):
                ref_path = _managed_path(root, snapshot.get("compare_image_url"))
                if ref_path is not None:
                    referenced.add(ref_path)
    return sources, referenced, active


def find_orphan_overlays(
    db, storage_root: Path, *,
    min_age_seconds: int = DEFAULT_MIN_AGE_SECONDS,
    now: float | None = None,
) -> list[dict]:
    """Read-only scan of exact, old, unreferenced attempt overlay filenames."""
    if min_age_seconds <= 0:
        raise ValueError("min_age_seconds must be positive")
    root = Path(storage_root).resolve()
    clock = time.time() if now is None else now
    sources, referenced, active = _references(db, root)
    candidates = []
    seen = set()
    for hw_id, source in sorted(sources.items()):
        if not source.exists() or not source.is_file() or source.is_symlink():
            continue
        for candidate in source.parent.glob(f"{source.stem}_result_*.jpg"):
            if candidate.is_symlink() or not candidate.is_file():
                continue
            match = ATTEMPT_RE.fullmatch(candidate.name)
            if not match or match.group(1) != source.stem:
                continue
            resolved = candidate.resolve()
            if not resolved.is_relative_to(root) or resolved in seen:
                continue
            if resolved in referenced or (hw_id, match.group(2)) in active:
                continue
            stat = candidate.stat()
            if stat.st_mtime > clock - min_age_seconds:
                continue
            seen.add(resolved)
            candidates.append({
                "relative_path": resolved.relative_to(root).as_posix(),
                "homework_id": hw_id,
                "attempt_id": match.group(2),
                "size_bytes": stat.st_size,
                "mtime_ns": stat.st_mtime_ns,
            })
    return sorted(candidates, key=lambda item: item["relative_path"])


def quarantine_orphan_overlays(
    session_factory, storage_root: Path, quarantine_dir: Path, *,
    writers_stopped: bool,
    min_age_seconds: int = DEFAULT_MIN_AGE_SECONDS,
    now: float | None = None,
) -> list[dict]:
    """Move only still-matching candidates to an off-/uploads quarantine.

    Operator must independently stop all application workers. Each attempted
    move is journaled before os.rename; on crash, both path and journal reveal
    whether it was moved. Quarantine must share a filesystem for atomic rename.
    """
    if not writers_stopped:
        raise ValueError("quarantine requires confirmed offline maintenance")
    root = Path(storage_root).resolve()
    quarantine = Path(quarantine_dir).resolve()
    if quarantine == root or root in quarantine.parents or quarantine in root.parents:
        raise ValueError("quarantine must be outside and not contain storage_root")
    quarantine.mkdir(parents=True, exist_ok=True)
    if quarantine.stat().st_dev != root.stat().st_dev:
        raise ValueError("quarantine and storage_root must be on the same filesystem")

    moved = []
    with session_factory() as db:
        candidates = find_orphan_overlays(
            db, root, min_age_seconds=min_age_seconds, now=now,
        )
        for record in candidates:
            original = root / record["relative_path"]
            target = quarantine / record["relative_path"]
            # Repeat the read-only eligibility check to catch stale plans or
            # changed DB references before any single-file mutation.
            db.expire_all()
            current = find_orphan_overlays(
                db, root, min_age_seconds=min_age_seconds, now=now,
            )
            if record not in current or not original.is_file() or original.is_symlink():
                continue
            if original.stat().st_mtime_ns != record["mtime_ns"]:
                continue
            target.parent.mkdir(parents=True, exist_ok=True)
            if target.exists() or target.is_symlink():
                raise FileExistsError(f"quarantine destination exists: {target}")
            entry = {"source": record["relative_path"], "target": str(target),
                     "action": "planned", "size_bytes": record["size_bytes"]}
            with (quarantine / "manifest.jsonl").open("a", encoding="utf-8") as stream:
                stream.write(json.dumps(entry, ensure_ascii=False) + "\n")
                stream.flush()
                os.fsync(stream.fileno())
            os.rename(original, target)
            moved.append(record)
    return moved
